<script setup lang="ts">
import type { NotificationRecord, Paginated } from '@lims/shared';

definePageMeta({ title: 'Message outbox', capabilities: ['admin'] });
useHead({ title: 'Message outbox' });

const api = useApi();
const toast = useToast();
const { dateTime } = useFormat();
const rows = ref<NotificationRecord[]>([]);
const loading = ref(true);
const error = ref<string | null>(null);
const channel = ref('');
const status = ref('');
const retrying = ref<string | null>(null);
const channelOptions = [
  { value: '', label: 'All channels' },
  { value: 'IN_APP', label: 'In-app' },
  { value: 'EMAIL', label: 'Email' },
  { value: 'SMS', label: 'SMS' },
  { value: 'WHATSAPP', label: 'WhatsApp' },
];
const statusOptions = [
  { value: '', label: 'All states' },
  { value: 'QUEUED', label: 'Queued' },
  { value: 'SENT', label: 'Sent' },
  { value: 'FAILED', label: 'Failed' },
  { value: 'SKIPPED', label: 'Skipped' },
];

async function load(): Promise<void> {
  loading.value = true;
  error.value = null;
  try {
    const result = await api.get<Paginated<NotificationRecord>>('/notifications/outbox', {
      limit: 100,
      ...(channel.value ? { channel: channel.value } : {}),
      ...(status.value ? { status: status.value } : {}),
    });
    rows.value = result.items;
  } catch (caught) {
    error.value = apiErrorMessage(caught);
  } finally {
    loading.value = false;
  }
}

async function retry(row: NotificationRecord): Promise<void> {
  retrying.value = row.id;
  try {
    await api.post(`/notifications/${row.id}/retry`);
    toast.success('Retry queued', 'The delivery attempt has been recorded.');
    await load();
  } catch (caught) {
    toast.error('Retry failed', apiErrorMessage(caught));
  } finally {
    retrying.value = null;
  }
}

function statusClass(value: string): string {
  if (value === 'SENT') return 'text-success border-success/40 bg-success/10';
  if (value === 'FAILED') return 'text-danger border-danger/40 bg-danger/10';
  if (value === 'SKIPPED') return 'text-muted border-line';
  return 'text-warning border-warning/40 bg-warning/10';
}

onMounted(load);
</script>

<template>
  <div>
    <PageHeader
      eyebrow="Communications"
      title="Message outbox"
      description="Every in-app, email, SMS and WhatsApp message with delivery state, provider and retry history."
    >
      <template #actions
        ><button type="button" class="btn btn-secondary" :disabled="loading" @click="load">
          <AppIcon name="refresh" :size="13" /> Refresh
        </button></template
      >
    </PageHeader>
    <AdminNav />

    <div class="mb-4 flex flex-wrap gap-2">
      <SearchSelect
        v-model="channel"
        :options="channelOptions"
        :full-width="false"
        class="w-auto"
        aria-label="Channel"
        placeholder="All channels"
        @change="load"
      />
      <SearchSelect
        v-model="status"
        :options="statusOptions"
        :full-width="false"
        class="w-auto"
        aria-label="Status"
        placeholder="All states"
        @change="load"
      />
      <span class="ml-auto self-center font-mono text-[9px] uppercase tracking-caps text-muted"
        >{{ rows.length }} messages</span
      >
    </div>

    <ErrorState v-if="error" :message="error" @retry="load" />
    <LoadingSkeleton v-else-if="loading" :rows="6" />
    <EmptyState
      v-else-if="rows.length === 0"
      icon="send"
      title="Outbox is empty"
      description="Messages generated by the portal, report release and QA workflows appear here."
    />
    <div v-else class="divide-y divide-line border border-line bg-surface">
      <article v-for="row in rows" :key="row.id" class="p-4">
        <div class="flex flex-wrap items-start justify-between gap-3">
          <div class="min-w-0">
            <div class="flex flex-wrap items-center gap-2">
              <span
                class="border px-1.5 py-0.5 font-mono text-[8px] uppercase tracking-caps text-muted"
                >{{ row.channel }}</span
              >
              <span
                class="border px-1.5 py-0.5 font-mono text-[8px] uppercase tracking-caps"
                :class="statusClass(row.status)"
                >{{ row.status }}</span
              >
              <span class="font-mono text-[8px] uppercase tracking-caps text-muted">{{
                row.type
              }}</span>
            </div>
            <p class="mt-2 text-sm font-medium">{{ row.title }}</p>
            <p class="mt-1 line-clamp-2 text-xs leading-relaxed text-muted">{{ row.body }}</p>
            <p class="mt-2 font-mono text-[9px] text-muted">
              {{ row.recipient ?? 'role / in-app' }} · {{ dateTime(row.createdAt) }}
            </p>
            <p v-if="row.lastError" class="mt-1 font-mono text-[9px] text-danger">
              {{ row.lastError }}
            </p>
          </div>
          <div class="flex shrink-0 flex-col items-end gap-1">
            <span class="font-mono text-[9px] text-muted">{{ row.provider ?? '—' }}</span>
            <button
              v-if="row.status === 'FAILED' && row.channel !== 'IN_APP'"
              type="button"
              class="btn btn-secondary btn-sm"
              :disabled="retrying === row.id"
              @click="retry(row)"
            >
              Retry
            </button>
          </div>
        </div>
      </article>
    </div>
  </div>
</template>
